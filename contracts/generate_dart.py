"""Generate dependency-free typed Dart codecs from our bounded schema subset."""
import json,re
from pathlib import Path
ROOT=Path(__file__).parent
OUT=ROOT.parent/'packages/protocol/lib/protocol.dart'
classes=[]
def lit(x):return json.dumps(x).replace("$", "\\$")
def pascal(s):return ''.join(w[0].upper()+w[1:] for w in re.split(r'[^A-Za-z0-9]+',s) if w)
def field(spec,name,expr):
    nullable=False
    if 'anyOf' in spec:
        spec=next(x for x in spec['anyOf'] if x.get('type')!='null');nullable=True
    else: spec=dict(spec)
    t=spec.get('type')
    if isinstance(t,list): nullable='null' in t; t=next(x for x in t if x!='null');spec['type']=t
    if not t and 'enum' in spec:t='string'
    if t=='object':
        emit(name,spec);typ=name;parse=f'{name}.fromJson(_map({expr}))';encode='VALUE.toJson()'
    elif t=='array':
        sub,parser,enc=field(spec['items'],name+'Item','item')
        typ=f'List<{sub}>';parse=f'_list({expr}, {spec.get("minItems",0)}, {spec.get("maxItems",2147483647)}).map((item) => {parser}).toList()'
        if spec.get('uniqueItems'):parse=f'_unique({parse})'
        encode=f'VALUE.map((item) => {enc.replace("VALUE","item")}).toList()'
    elif t=='integer':typ='int';parse=f'_integer({expr}, {spec.get("minimum",0)}, {spec.get("maximum",9007199254740991)})';encode='VALUE'
    elif t=='boolean':typ='bool';parse=f'_boolean({expr})';encode='VALUE'
    else:
        typ='String';parse=f'_string({expr}, {spec.get("minLength",0)}, {spec.get("maxLength",2147483647)})';encode='VALUE'
        if 'enum' in spec:parse=f'_choice({parse}, {lit(spec["enum"])})'
        if 'pattern' in spec:parse=f'_pattern({parse}, {lit(spec["pattern"])})'
        if spec.get('format')=='uuid':parse=f'_uuid({parse})'
        if spec.get('format')=='date-time':parse=f'_dateTime({parse})'
    if nullable:
        typ+='?';parse=f'{expr} == null ? null : {parse}';encode='VALUE == null ? null : '+encode.replace('VALUE','VALUE!')
    return typ,parse,encode

def emit(name,spec):
    props=spec['properties'];required=set(spec['required']);defs=[];params=[];args=[];pairs=[];checks=[]
    for key,sub in props.items():
        expr=f'json[{lit(key)}]'
        if 'const' in sub:
            val=lit(sub['const']);typ='bool' if isinstance(sub['const'],bool) else 'int' if isinstance(sub['const'],int) else 'String'
            defs.append(f'  {typ} get {key} => {val};');checks.append(f'    _constant({expr}, {val});');pairs.append(f'{lit(key)}: {val}');continue
        typ,parse,enc=field(sub,name+pascal(key),expr)
        optional=key not in required
        if optional and not typ.endswith('?'):
            checks.append(f'    if (json.containsKey({lit(key)}) && {expr} == null) _bad();')
            typ+='?';parse=f'{expr} == null ? null : {parse}';enc='VALUE!'
        defs.append(f'  final {typ} {key};')
        params.append(('required ' if not optional else '')+f'this.{key}')
        args.append(f'{key}: {parse}')
        pairs.append((f'if ({key} != null) ' if optional else '')+f'{lit(key)}: '+enc.replace('VALUE',key))
    ctor=f'  {name}({{{", ".join(params)}}});' if params else f'  {name}();'
    code=f'class {name} implements WireModel {{\n'+ '\n'.join(defs)+'\n'+ctor+'\n'
    code+=f'  factory {name}.fromJson(Map<String, dynamic> json) {{\n    _shape(json, {lit(list(props))}, {lit(spec['required'])});\n'+'\n'.join(checks)+f'\n    return {name}('+', '.join(args)+');\n  }\n'
    code+=f'  @override\n  Map<String, dynamic> toJson() {{\n    final json = <String, dynamic>{{'+', '.join(pairs)+f'}};\n    {name}.fromJson(json);\n    return json;\n  }}\n}}\n'
    classes.append(code)
header='''// GENERATED by contracts/generate_dart.py. Edit schemas/generator, not this file.
// Local codecs enforce the supported schema subset; server authentication is separate.
abstract interface class WireModel { Map<String, dynamic> toJson(); }
Never _bad() => throw const FormatException('Invalid protocol message');
Map<String,dynamic> _map(dynamic v) => v is Map<String,dynamic> ? v : _bad();
void _shape(Map<String,dynamic> v, List<String> allowed, List<String> required) {
 if (v.keys.any((k) => !allowed.contains(k)) || required.any((k) => !v.containsKey(k))) _bad();
}
void _constant(dynamic v,dynamic expected) { if(v != expected) _bad(); }
String _string(dynamic v,int min,int max) => v is String && v.runes.length>=min && v.runes.length<=max ? v : _bad();
String _choice(String v,List<String> choices) => choices.contains(v) ? v : _bad();
String _pattern(String v,String pattern) => RegExp(pattern).hasMatch(v) ? v : _bad();
String _uuid(String v) => RegExp(r'^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$').hasMatch(v) ? v : _bad();
String _dateTime(String v) => DateTime.tryParse(v)!=null && RegExp(r'(Z|[+-][0-9]{2}:[0-9]{2})$').hasMatch(v) ? v : _bad();
int _integer(dynamic v,int min,int max) => v is int && v>=min && v<=max ? v : _bad();
bool _boolean(dynamic v) => v is bool ? v : _bad();
List<dynamic> _list(dynamic v,int min,int max) => v is List && v.length>=min && v.length<=max ? v : _bad();
List<T> _unique<T>(List<T> v) => v.toSet().length==v.length ? v : _bad();
'''
factories=[]
for filename,prefix,factory in [('client-event','Client','clientEventFromJson'),('server-event','Server','serverEventFromJson'),('wake-registration','WakeRegistration','wakeRegistrationFromJson')]:
    schema=json.loads((ROOT/'v0.1'/f'{filename}.schema.json').read_text());key='provider' if filename=='wake-registration' else 'type';cases=[]
    for sub in schema['oneOf']:
        kind=sub['properties'][key]['const'];name=prefix+pascal(kind);emit(name,sub);cases.append(f'case {lit(kind)}: return {name}.fromJson(json);')
    factories.append(f'WireModel {factory}(Map<String,dynamic> json) {{ switch(json[{lit(key)}]) {{'+''.join(cases)+'default: return _bad(); }}')
for file,name in [('create','CreateRequest'),('join','JoinRequest'),('create-response','CreateResponse'),('join-response','JoinResponse')]:emit(name,json.loads((ROOT/'v0.1'/f'{file}.schema.json').read_text()))
OUT.parent.mkdir(parents=True,exist_ok=True);OUT.write_text(header+'\n'.join(classes+factories))
